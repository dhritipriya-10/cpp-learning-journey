//Printing all odd no.s without using if condition
#include<bits/stdc++.h>
using namespace std;
void pgm4(){
    for(int i = 1; i <= 20; i+=2) { //i = 1 starts from 1 and then increment by i +=2 i.e 1 + 2 = 3, 3 + 2 = 5, 5 + 2 = 7... 
        cout<< i << endl;
    }
}
int main() {
    pgm4();
    return 0;
}